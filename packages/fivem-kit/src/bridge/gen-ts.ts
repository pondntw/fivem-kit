import type { Bridge, Field, TypeNode } from './schema.ts';

const HEADER = `// AUTO-GENERATED by fivem-kit from bridge.json. Do not edit by hand.
// Change bridge.json, then run \`npx fivem-kit gen\` (fivem-kit dev does it for you).
`;

function renderType(type: TypeNode, indent: string): string {
  switch (type.kind) {
    case 'primitive':
      return type.name === 'any' ? 'unknown' : type.name;
    case 'array': {
      const inner = renderType(type.of, indent);
      return type.of.kind === 'primitive' ? `${inner}[]` : `Array<${inner}>`;
    }
    case 'object':
      return renderFields(type.fields, indent);
  }
}

function renderFields(fields: Field[], indent: string): string {
  if (fields.length === 0) return 'Record<string, never>';
  const inner = indent + '  ';
  const lines = fields.map((f) => `${inner}${f.name}${f.optional ? '?' : ''}: ${renderType(f.type, inner)};`);
  return `{\n${lines.join('\n')}\n${indent}}`;
}

export function generateTs(bridge: Bridge): string {
  const out: string[] = [HEADER];

  out.push('/** Messages Lua sends to the UI (client: `Ui.<name>(data)`, UI: `useNuiEvent`). */');
  out.push('export interface UiMessages {');
  for (const m of bridge.toUi) out.push(`  ${m.name}: ${renderFields(m.fields, '  ')};`);
  out.push('}', '');

  out.push('/** Callbacks the UI calls (UI: `fetchNui`, client: `Nui.<name>(handler)`). */');
  out.push('export interface NuiCallbacks {');
  for (const c of bridge.toClient) {
    out.push(`  ${c.name}: {`);
    out.push(`    request: ${renderFields(c.request, '    ')};`);
    out.push(`    response: ${renderFields(c.response, '    ')};`);
    out.push('  };');
  }
  out.push('}', '');

  out.push(`export const uiMessageNames = ${JSON.stringify(bridge.toUi.map((m) => m.name))} as const;`);
  out.push(`export const nuiCallbackNames = ${JSON.stringify(bridge.toClient.map((c) => c.name))} as const;`);
  out.push('');
  return out.join('\n');
}
