import type { Bridge, Field, TypeNode } from './schema.ts';

const HEADER = `-- AUTO-GENERATED by fivem-kit from bridge.json. Do not edit by hand.
-- Change bridge.json, then run \`npx fivem-kit gen\` (fivem-kit dev does it for you).
-- The ---@class annotations give you autocomplete and type checks with the Lua Language Server.
`;

/**
 * Emits LuaLS classes for a field list. Nested objects become their own class
 * named after their path (e.g. NuiRequest.buy.meta), so autocomplete works all the way down.
 */
class ClassWriter {
  readonly lines: string[] = [];

  luaType(type: TypeNode, className: string): string {
    switch (type.kind) {
      case 'primitive':
        return type.name;
      case 'array':
        return `${this.luaType(type.of, className)}[]`;
      case 'object':
        this.writeClass(className, type.fields);
        return className;
    }
  }

  writeClass(name: string, fields: Field[]): void {
    // Render nested classes first into a separate buffer so each class block stays contiguous.
    const nested = new ClassWriter();
    const fieldLines = fields.map((f) => {
      const t = nested.luaType(f.type, `${name}.${f.name}`);
      return `---@field ${f.name}${f.optional ? '?' : ''} ${t}`;
    });
    this.lines.push(`---@class ${name}`, ...fieldLines, '');
    this.lines.push(...nested.lines);
  }
}

export function generateLua(bridge: Bridge): string {
  const types = new ClassWriter();
  for (const m of bridge.toUi) types.writeClass(`UiMessage.${m.name}`, m.fields);
  for (const c of bridge.toClient) {
    types.writeClass(`NuiRequest.${c.name}`, c.request);
    types.writeClass(`NuiResponse.${c.name}`, c.response);
  }

  const out: string[] = [HEADER, ...types.lines];

  out.push('---Send messages to the UI. Each function wraps SendNUIMessage.');
  out.push('Ui = Ui or {}', '');
  for (const m of bridge.toUi) {
    out.push(`---Send \`${m.name}\` to the UI (received with useNuiEvent('${m.name}', ...)).`);
    out.push(`---@param data UiMessage.${m.name}`);
    out.push(`function Ui.${m.name}(data)`);
    out.push(`    SendNUIMessage({ action = '${m.name}', data = data or {} })`);
    out.push('end', '');
  }

  out.push('---Answer calls from the UI. Each function wraps RegisterNUICallback.');
  out.push('---If the handler errors, the UI\'s fetchNui rejects instead of hanging.');
  out.push('Nui = Nui or {}', '');
  out.push('local function respond(name, handler, data, cb)');
  out.push('    local ok, result = pcall(handler, data or {})');
  out.push('    if not ok then');
  out.push(`        print(('^1[%s] NUI callback "%s" failed: %s^0'):format(GetCurrentResourceName(), name, tostring(result)))`);
  out.push('        return cb({ __error = tostring(result) })');
  out.push('    end');
  out.push('    cb(result or {})');
  out.push('end', '');
  for (const c of bridge.toClient) {
    out.push(`---Handle \`${c.name}\`, called from the UI with fetchNui('${c.name}', ...).`);
    out.push(`---@param handler fun(data: NuiRequest.${c.name}): NuiResponse.${c.name}?`);
    out.push(`function Nui.${c.name}(handler)`);
    out.push(`    RegisterNUICallback('${c.name}', function(data, cb) respond('${c.name}', handler, data, cb) end)`);
    out.push('end', '');
  }
  return out.join('\n');
}
